import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

def neville(x_eval, x_nodos, y_nodos):
    x = np.asarray(x_nodos, dtype=float)
    y = np.asarray(y_nodos, dtype=float)

    n = len(x) - 1
    Q = np.zeros((n + 1, n + 1), dtype=float)

    # Columna inicial Q_{i,0} = f(x_i)
    Q[:, 0] = y

    # Construcción iterativa de la tabla de Neville (Algoritmo 3.1)
    for i in range(1, n + 1):
        for j in range(1, i + 1):
            numerador = (x_eval - x[i - j]) * Q[i, j - 1] - (x_eval - x[i]) * Q[i - 1, j - 1]
            denominador = x[i] - x[i - j]
            Q[i, j] = numerador / denominador

    return Q

"""**3.- EJECUCION DE LA TABLA Y GRAFICA**"""

# Datos del Ejemplo
x_datos = [1.0, 1.3, 1.6, 1.9, 2.2]
y_datos = [0.7651977, 0.6200860, 0.4554022, 0.2818186, 0.1103623]
x_objetivo = 1.5

# Cálculo de la tabla Q
Q_matriz = neville(x_objetivo, x_datos, y_datos)
resultado_final = Q_matriz[-1, -1]

# Presentación tabular limpia con pandas
nombres_col = [f"Q_i,{j}" for j in range(len(x_datos))]
df = pd.DataFrame(Q_matriz, columns=nombres_col)
df.insert(0, "x_i", x_datos)

# Ocultamos los ceros de la parte triangular superior para mejor lectura
df_limpio = df.astype(object)
for i in range(len(x_datos)):
    for j in range(i + 1, len(x_datos)):
        df_limpio.iloc[i, j + 1] = ""

display(df_limpio)
print(f"\nAproximación final P({x_objetivo}) = {resultado_final:.7f}")

# Gráfica del polinomio interpolante y el punto evaluado
x_curva = np.linspace(min(x_datos), max(x_datos), 200)
y_curva = [neville(val, x_datos, y_datos)[-1, -1] for val in x_curva]

plt.figure(figsize=(8, 4.5))
plt.plot(x_curva, y_curva, color="#1F618D", linewidth=2, label="Polinomio interpolante $P_4(x)$")
plt.scatter(x_datos, y_datos, color="#154360", s=50, zorder=5, label="Nodos tabulados $(x_i, f(x_i))$")
plt.scatter([x_objetivo], [resultado_final], color="#B03A2E", s=90, zorder=6,
            label=f"Punto evaluado: $P_4({x_objetivo}) \\approx {resultado_final:.7f}$")

plt.title("Interpolación Iterada de Neville — Ejemplo 2 (Burden)", fontsize=12, fontweight="bold")
plt.xlabel("$x$")
plt.ylabel("$f(x)$")
plt.grid(True, linestyle="--", alpha=0.5)
plt.legend()
plt.tight_layout()
plt.show()

